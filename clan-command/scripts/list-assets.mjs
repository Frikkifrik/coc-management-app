/**
 * Regenerates `public/clash-assets/EXPECTED.md` — the checklist of every path
 * the app resolves when drawing a tile, and how many of those are backed by a
 * real file in the repository.
 *
 *   npm run assets:list
 *
 * Two sources count as installed: the generated Arsenaal map (the official drop,
 * in the Drive's own nested layout) and a hand drop at the flat
 * `<category>/<slug>.png` paths. Neither is generated artwork.
 */
import { build } from 'esbuild';
import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const assetRoot = path.join(root, 'public', 'clash-assets');
const outfile = path.join(root, 'node_modules', '.clash-assets-list.mjs');

await build({
  stdin: {
    contents: `export { expectedAssetPaths } from './src/clash/assets';`,
    resolveDir: root,
    sourcefile: 'assets-entry.ts',
    loader: 'ts',
  },
  outfile,
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  absWorkingDir: root,
  logLevel: 'silent',
});

const { expectedAssetPaths } = await import(pathToFileURL(outfile).href);
const paths = expectedAssetPaths();

/** Every file under clash-assets/, at any depth, as a `/clash-assets/...` URL. */
function walk(dir, base = '') {
  const out = [];
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const rel = base ? `${base}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...walk(path.join(dir, entry.name), rel));
    else out.push(`/clash-assets/${rel}`);
  }
  return out;
}

const present = new Set(walk(assetRoot));
const isInstalled = (item) => present.has(item.path);

const installedTotal = paths.filter(isInstalled).length;
const mappedTotal = paths.filter((item) => item.mapped).length;

/** Group by the app category the key belongs to, not by the folder on disk. */
const byCategory = new Map();
for (const item of paths) {
  const category = item.key.startsWith('category:') ? item.key.slice(9) : item.key.split(':')[0];
  const bucket = byCategory.get(category) ?? [];
  bucket.push(item);
  byCategory.set(category, bucket);
}

const lines = [
  '# Expected artwork',
  '',
  'Generated by `npm run assets:list` — do not edit by hand.',
  '',
  'Every path the app resolves when drawing a tile. A tile uses the first of these',
  'that exists: a real file in this folder, then a live Supercell `iconUrl`, then a',
  'neutral typographic mark. **No generated artwork belongs in this folder.**',
  '',
  'The official drop keeps the Drive’s own layout (`heroes/archer_queen/icon.webp`,',
  '`buildings/home-village/inferno_tower/level_11.webp`); `npm run assets:map` maps',
  'those files onto catalog keys. To fill a gap by hand instead, drop a PNG at the',
  'flat path shown — `<category>/<slug>.png`.',
  '',
  `**${paths.length} paths · ${installedTotal} installed · ${mappedTotal} from the Arsenaal map · ${
    paths.length - installedTotal
  } unresolved**`,
  '',
  'See `DRIVE_SOURCE.md` for where the drop came from and the read-only policy.',
  '',
];

for (const [category, items] of byCategory) {
  const installed = items.filter(isInstalled).length;
  lines.push(
    `## ${category}`,
    '',
    `${installed}/${items.length} resolved`,
    '',
    '| Catalog key | Resolved file | |',
    '| --- | --- | --- |',
  );
  for (const item of items) {
    const rel = item.path.replace('/clash-assets/', '');
    lines.push(`| \`${item.key}\` | \`${rel}\` | ${isInstalled(item) ? '✅' : '— no artwork in the drop'} |`);
  }
  lines.push('');
}

mkdirSync(assetRoot, { recursive: true });
writeFileSync(path.join(assetRoot, 'EXPECTED.md'), `${lines.join('\n')}\n`);

const fileCount = present.size;
const bytes = [...present].reduce((sum, url) => {
  try {
    return sum + statSync(path.join(root, 'public', url)).size;
  } catch {
    return sum;
  }
}, 0);

console.log(
  `Wrote public/clash-assets/EXPECTED.md — ${paths.length} paths, ${installedTotal} installed ` +
    `(${mappedTotal} from the Arsenaal map, ${installedTotal - mappedTotal} hand-dropped), ` +
    `${paths.length - installedTotal} unresolved.`,
);
console.log(`Folder holds ${fileCount} files, ${(bytes / 1024 / 1024).toFixed(1)} MB.`);
