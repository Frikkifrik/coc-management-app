/**
 * Regenerates `public/clash-assets/EXPECTED.md` — the checklist of every path
 * the app will look for when resolving official artwork.
 *
 *   npm run assets:list
 *
 * Drop files at those paths (PNG) and the tiles pick them up on the next load.
 */
import { build } from 'esbuild';
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const assetRoot = path.join(root, 'public', 'clash-assets');
const outfile = path.join(root, 'node_modules', '.clash-assets-list.mjs');

await build({
  stdin: {
    contents: `export { expectedAssetPaths } from './src/clash/assets';`,
    resolveDir: root,
    sourcefile: 'assets-entry.ts',
    loader: 'ts',
  },
  outfile,
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  absWorkingDir: root,
  logLevel: 'silent',
});

const { expectedAssetPaths } = await import(pathToFileURL(outfile).href);
const paths = expectedAssetPaths();

const present = new Set();
if (existsSync(assetRoot)) {
  for (const dir of readdirSync(assetRoot, { withFileTypes: true })) {
    if (!dir.isDirectory()) continue;
    for (const file of readdirSync(path.join(assetRoot, dir.name))) {
      present.add(`/clash-assets/${dir.name}/${file}`);
    }
  }
}

const installedTotal = paths.filter((item) => present.has(item.path)).length;

const byFolder = new Map();
for (const item of paths) {
  const folder = item.path.split('/')[2];
  const bucket = byFolder.get(folder) ?? [];
  bucket.push(item);
  byFolder.set(folder, bucket);
}

const lines = [
  '# Expected artwork',
  '',
  'Generated by `npm run assets:list` — do not edit by hand.',
  '',
  'Every path the app tries when resolving a tile. Drop an official Clash of Clans',
  'PNG at any of these paths and the tile renders it on the next page load. Missing',
  'files fall back to a live Supercell `iconUrl`, then to a neutral typographic mark.',
  '**No generated artwork belongs in this folder.**',
  '',
  `${paths.length} paths in total · ${installedTotal} installed`,
  '',
];

for (const [folder, items] of byFolder) {
  const installed = items.filter((item) => present.has(item.path)).length;
  lines.push(`## ${folder}/`, '', `${installed}/${items.length} installed`, '', '| Path | Catalog key | |', '| --- | --- | --- |');
  for (const item of items) {
    const rel = item.path.replace('/clash-assets/', '');
    lines.push(`| \`${rel}\` | \`${item.key}\` | ${present.has(item.path) ? '✅' : ''} |`);
  }
  lines.push('');
}

mkdirSync(assetRoot, { recursive: true });
writeFileSync(path.join(assetRoot, 'EXPECTED.md'), `${lines.join('\n')}\n`);
console.log(`Wrote public/clash-assets/EXPECTED.md — ${paths.length} paths, ${installedTotal} installed.`);
